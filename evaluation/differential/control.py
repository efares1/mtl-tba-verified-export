"""Negative control: does the word distribution detect off-by-one errors?
For each pair (formula f, mutated formula g) the automaton of !g (generated by mtl2tba) is
compared with the judge on f.  The number of words (of N) on which they differ shows how
sensitive the test is to boundary mistakes.  Usage (WSL): python3 control.py N SEED"""
import os, random, subprocess, sys, tempfile, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dlib import *
EV = os.path.join(HERE, '..')
EXE = os.path.join(EV, '..', 'tool', '_build', 'default', 'src', 'mtl2tba.exe')
N, SEED = int(sys.argv[1]), int(sys.argv[2])

PAIRS = [
    ('F1', '[](p -> <>[<=5] q)', '[](p -> <>[<5] q)'),
    ('F1', '[](p -> <>[<=5] q)', '[](p -> <>[<=4] q)'),
    ('F1', '[](p -> <>[<=5] q)', '[](p -> <>[<=6] q)'),
    ('F5', '[](p -> <>[>=2] q)', '[](p -> <>[>2] q)'),
    ('F5', '[](p -> <>[>=2] q)', '[](p -> <>[>=3] q)'),
    ('F2', '[](p -> [][<=3] q)', '[](p -> [][<3] q)'),
    ('F4', '[](p -> (p U[<=4] q))', '[](p -> (p U[<4] q))'),
    ('F7', '[]<>[<=5] p', '[]<>[<5] p'),
    ('F8', '[]<>[>=2] p', '[]<>[>2] p'),
    ('F11', '(<>[<=5] p) & ([][<2] !p)', '(<>[<=5] p) & ([][<=2] !p)'),
    ('F12', '[](p -> (<>[<=5] q & [][<2] !q))', '[](p -> (<>[<=5] q & [][<=2] !q))'),
    ('N3', '<>[<=5](p1 & <>[<=5](p2 & <>[<=5] p3))', '<>[<=5](p1 & <>[<5](p2 & <>[<=5] p3))'),
]


def main():
    rng = random.Random(SEED)
    import run_diff_words as rw
    print('id\tjudged_formula\tautomaton_of\twords\tdiffering_words')
    for fid, f, g in PAIRS:
        w = tempfile.mkdtemp()
        subprocess.run([EXE, '-nopdf', '-o', os.path.join(w, 'o'), '!(%s)' % g], cwd=w, capture_output=True, timeout=120)
        aut = OursAut(os.path.join(w, 'o.xml'))
        shutil.rmtree(w, ignore_errors=True)
        pf = parse_mtl(f)
        props = sorted(mtl_props(pf) | mtl_props(parse_mtl(g)))
        consts = rw.constants(pf) | rw.constants(parse_mtl(g))
        diff = 0
        for _ in range(N):
            word = rw.random_word(rng, props, consts)
            exp = not judge(pf, word)
            if aut.accepts(word) != exp:
                diff += 1
        print('%s\t%s\t%s\t%d\t%d' % (fid, f, g, N, diff), flush=True)


import threading
threading.stack_size(256 * 1024 * 1024)
sys.setrecursionlimit(1000000)
t = threading.Thread(target=main); t.start(); t.join()
