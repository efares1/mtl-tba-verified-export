"""Collect results/*.json and counterexamples/*.json into RESULTS.md and mutation_table.tex.
Run on Windows or WSL: python3 make_report.py"""
import json, os, glob, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mutants
BS = chr(92)

verdict = {}   # id -> (class, note)  filled from verdicts.json (hand-checked classification)
vp = os.path.join(HERE, 'verdicts.json')
if os.path.exists(vp):
    verdict = json.load(open(vp))

rows = []
for (mid, passname, desc, why, old, new) in mutants.M:
    p = os.path.join(HERE, 'results', mid + '.json')
    r = json.load(open(p)) if os.path.exists(p) else None
    try:
        line = mutants.patched_source(mid)[1]
    except Exception:
        line = '?'
    rows.append((mid, passname, desc, why, line, r))

def t2(r):
    c, b = r['T2_corpus'], r['T2_bench']
    if not c and not b:
        return 'none (budget %d)' % r['budget_tried'], None
    best = []
    if c: best.append((c['budget'], c['min_first_word'], c['inputs_with_mismatch'], 'corpus'))
    if b: best.append((b['budget'], b['min_first_word'], b['inputs_with_mismatch'], 'bench'))
    return best, True

out = []
out.append('# Mutation study: what testing misses and the preservation theorems exclude\n')
out.append('Generated by make_report.py from results/*.json and verdicts.json.\n')
out.append('| id | pass | line | T1 corpus changed | T1 bench changed | crash | T2 corpus (budget, inputs, first word) | T2 bench | class |')
out.append('|---|---|---|---|---|---|---|---|---|')
for (mid, passname, desc, why, line, r) in rows:
    if r is None:
        out.append('| %s | %s | %s | not run | | | | | |' % (mid, passname, line)); continue
    c, b = r['T2_corpus'], r['T2_bench']
    cs = '%d words: %d inputs, first %s' % (c['budget'], c['inputs_with_mismatch'], c['min_first_word']) if c and c['inputs_with_mismatch'] else 'no mismatch (%d words)' % r['budget_tried']
    bs = '%d words: %d inputs, first %s' % (b['budget'], b['inputs_with_mismatch'], b['min_first_word']) if b and b['inputs_with_mismatch'] else 'no mismatch (%d words)' % r['budget_tried']
    cl = verdict.get(mid, {}).get('class', '?')
    out.append('| %s | %s | %s | %d/%d | %d/%d | %d+%d | %s | %s | %s |' % (mid, passname, line, r['T1_corpus_changed'], r['corpus_runs'], r['T1_bench_changed'], r['bench_runs'], r['crashes'], r['bench_crashes'], cs, bs, cl))
open(os.path.join(HERE, 'RESULTS_table.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
