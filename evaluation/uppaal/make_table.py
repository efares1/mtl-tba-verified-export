"""Summarize results.tsv: summary.md (all groups) and uppaal_table.tex (compact LaTeX table).

    python make_table.py
"""
import csv, os, re, collections

HERE = os.path.dirname(os.path.abspath(__file__))
BS = chr(92)
rows = list(csv.DictReader(open(os.path.join(HERE, 'results.tsv'), encoding='utf8'), delimiter=chr(9)))
by = {r['name']: r for r in rows}

def prop_edges(name):
    x = open(os.path.join(HERE, 'models', name + '.xml'), encoding='utf8').read()
    t = re.search(r'<template>\s*<name>Property</name>.*?</template>', x, re.S).group(0)
    return len(re.findall(r'<transition>', t)), len(re.findall(r'<location ', t))

VARS = ['ours_default', 'ours_n0', 'ours_allcopy', 'casaal_plain', 'casaal_n0', 'casaal_opt', 'casaal_allcopy']
groups = collections.OrderedDict()
for r in rows:
    groups.setdefault((r['block'], r['case'], r['system']), {})[r['variant']] = r

# ---- summary.md
md = ['# UPPAAL 5.0.0 results (generated by make_table.py)', '',
      'Cells: stored/explored states, median wall time of 3 runs in s (verifyta -u -s -q -t0 -o 0).', '']
nv = collections.Counter(r['agree'] for r in rows)
md.append('Verdicts agree with the expected verdict in %d of %d runs with an expectation; disagreements: %d; '
          'acceptance-only checks (positive form): %d.' % (nv['yes'], nv['yes'] + nv['NO'], nv['NO'], nv['n/a']))
md.append('')
md.append('| block | case | system | ' + ' | '.join(VARS) + ' | same stored in all variants |')
md.append('|---|---|---|' + '---|' * (len(VARS) + 1))
for (blk, case, sysn), vs in groups.items():
    cells = []
    for v in VARS:
        r = vs.get(v)
        cells.append('%s/%s, %s s' % (r['stored'], r['explored'], r['wall_s']) if r else '-')
    stored = {vs[v]['stored'] for v in VARS if v in vs}
    full = blk in ('free', 'par') and sysn in ('free', 'parok') or (blk == 'neg' and sysn == 'ok')
    md.append('| %s | %s | %s | %s | %s |' % (blk, case, sysn, ' | '.join(cells),
              ('yes' if len(stored) == 1 else 'NO (%s)' % ','.join(sorted(stored))) + ('' if full else ' (partial: query satisfied, search stops)')))
open(os.path.join(HERE, 'summary.md'), 'w', encoding='utf8').write('\n'.join(md) + '\n')

# ---- LaTeX table: full explorations only (parok = whole reachable state space of the product)
sel = [('R3', 'parok'), ('R4', 'parok'), ('R5', 'parok'), ('R6', 'parok'), ('N4', 'free'), ('N5', 'free')]
tex = [BS + 'begin{tabular}{llrrrrrr}', BS + 'toprule',
       'Req. & System & Stored & ' + BS + 'multicolumn{4}{c}{Time (s)} & Prop. edges ' + BS + BS,
       BS + 'cmidrule(lr){4-7}',
       ' & & (all variants) & ours & ours all-copy & CASAAL & CASAAL+export & ours/CASAAL ' + BS + BS, BS + 'midrule']
for case, sysn in sel:
    key = [k for k in groups if k[1] == case and k[2] == sysn]
    if not key: continue
    vs = groups[key[0]]
    st = {vs[v]['stored'] for v in VARS if v in vs}
    stored = list(st)[0] if len(st) == 1 else '/'.join(sorted(st))
    pe_o = prop_edges(vs['ours_default']['name'])[0]
    pe_c = prop_edges(vs['casaal_plain']['name'])[0] if 'casaal_plain' in vs else None
    t = lambda v: vs[v]['wall_s'] if v in vs else '--'
    sysl = 'par-ok' if sysn == 'parok' else 'free'
    tex.append('%s & %s & %s & %s & %s & %s & %s & %s ' % (case, sysl, stored, t('ours_default'), t('ours_allcopy'),
               t('casaal_plain'), t('casaal_opt'), '%d/%s' % (pe_o, pe_c if pe_c is not None else '--')) + BS + BS)
tex += [BS + 'bottomrule', BS + 'end{tabular}']
open(os.path.join(HERE, 'uppaal_table.tex'), 'w', encoding='utf8').write('\n'.join(tex) + '\n')
print(open(os.path.join(HERE, 'uppaal_table.tex'), encoding='utf8').read())
